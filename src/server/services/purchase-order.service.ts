import 'server-only';

/**
 * Purchase order lifecycle + concurrent, idempotent stock receipt
 * (Rules 052, 075–080, 088, 126, 142, 147).
 *
 * Every method runs against a `CommerceStore`, so the identical logic is
 * exercised by PostgreSQL and by the in-memory concurrency harness.
 */
import { randomUUID } from 'node:crypto';
import { addMoney, calculateLineTotalCents, calculateTaxCents } from '../../lib/money';
import type { MemberRole } from '../middleware/with-auth';
import {
  InventoryLedgerService,
  LedgerInsufficientStockError,
  LedgerValidationError,
  type CommerceStore,
  type PoHeader,
  type PoItem,
  type PoListFilters,
  type PoStatus,
  type ReferenceMovement,
  type AuditInput,
} from './inventory-ledger.service';

export interface PoErrorShape {
  status: number;
  code: string;
  message: string;
  details: unknown;
}

/** Translate a domain error into an HTTP shape, or `null` if unrecognised. */
export function toPoError(error: unknown): PoErrorShape | null {
  if (
    error instanceof PoNotFoundError ||
    error instanceof PoStateError ||
    error instanceof PoForbiddenError ||
    error instanceof PoOverReceiptConflictError
  ) {
    return {
      status: error.status,
      code: error.code,
      message: error.message,
      details: 'details' in error ? error.details : null,
    };
  }
  if (error instanceof LedgerInsufficientStockError) {
    return { status: error.status, code: error.code, message: error.message, details: error.details };
  }
  if (error instanceof LedgerValidationError) {
    return { status: error.status, code: error.code, message: error.message, details: error.details };
  }
  return null;
}

export class PoNotFoundError extends Error {
  readonly code = 'PO_NOT_FOUND';
  readonly status = 404;
  constructor(poId: string) {
    super(`Purchase order ${poId} was not found.`);
    this.name = 'PoNotFoundError';
  }
}

export class PoStateError extends Error {
  readonly code = 'INVALID_PO_STATE_TRANSITION';
  readonly status = 409;
  constructor(message: string) {
    super(message);
    this.name = 'PoStateError';
  }
}

export class PoForbiddenError extends Error {
  readonly code = 'FORBIDDEN';
  readonly status = 403;
  constructor(message: string) {
    super(message);
    this.name = 'PoForbiddenError';
  }
}

export interface OverReceiptLine {
  productVariantId: string;
  sku: string;
  orderedQty: number;
  alreadyReceivedQty: number;
  attemptedQty: number;
  remainingReceivableQty: number;
}

export interface OverReceiptDetails {
  status: PoStatus;
  poNumber: string;
  lines: OverReceiptLine[];
}

export class PoOverReceiptConflictError extends Error {
  readonly code = 'OVER_RECEIPT_PREVENTED';
  readonly status = 409;
  constructor(
    message: string,
    readonly details: OverReceiptDetails,
  ) {
    super(message);
    this.name = 'PoOverReceiptConflictError';
  }
}

export interface PoActor {
  memberId: string;
  role: MemberRole;
  correlationId: string;
  ipAddress?: string | null;
  userAgent?: string | null;
}

export interface CreatePoInput {
  supplierId: string;
  locationId: string;
  currency: string;
  expectedDeliveryDate?: string;
  taxCents?: number;
  taxRateBps?: number;
  shippingCents: number;
  notes?: string;
  /** Set by the automation engine when generating a reorder PO (Rule 141). */
  isAutoGenerated?: boolean;
  items: Array<{ productVariantId: string; orderedQty: number; unitCostCents: number }>;
}

export interface PoDetail {
  purchaseOrder: PoHeader;
  items: Array<PoItem & { remainingQty: number; lineTotalCents: number }>;
  movements: ReferenceMovement[];
  timeline: AuditInput[];
}

export interface ReceivePoInput {
  items: Array<{ productVariantId: string; receiveQty: number; notes?: string }>;
  receiptNotes?: string;
}

export const PurchaseOrderService = {
  async listPurchaseOrders(store: CommerceStore, organizationId: string, filters: PoListFilters): Promise<PoHeader[]> {
    return store.listPos(organizationId, filters);
  },

  async getPurchaseOrderDetail(store: CommerceStore, organizationId: string, poId: string): Promise<PoDetail> {
    const purchaseOrder = await store.getPo(organizationId, poId);
    if (!purchaseOrder) throw new PoNotFoundError(poId);
    const items = (await store.listPoItems(organizationId, poId)).map((item) => ({
      ...item,
      remainingQty: Math.max(0, item.orderedQty - item.receivedQty),
      lineTotalCents: calculateLineTotalCents(item.orderedQty, item.unitCostCents),
    }));
    const movements = await store.listMovementsForReference(organizationId, poId);
    const timeline = await store.listAuditsForEntity(organizationId, poId);
    return { purchaseOrder, items, movements, timeline };
  },

  async createDraftPo(store: CommerceStore, organizationId: string, actor: PoActor, input: CreatePoInput): Promise<PoHeader> {
    const lineTotals = input.items.map((item) => calculateLineTotalCents(item.orderedQty, item.unitCostCents));
    const subtotalCents = lineTotals.reduce((sum, line) => addMoney(sum, line, input.currency, input.currency), 0);
    const taxCents =
      input.taxCents ?? (input.taxRateBps !== undefined ? calculateTaxCents(subtotalCents, input.taxRateBps) : 0);

    const poId = randomUUID();
    const header: PoHeader = {
      id: poId,
      organizationId,
      poNumber: await store.nextPoNumber(organizationId),
      supplierId: input.supplierId,
      locationId: input.locationId,
      status: 'DRAFT',
      currency: input.currency,
      subtotalCents,
      taxCents,
      shippingCents: input.shippingCents,
      totalCents: subtotalCents + taxCents + input.shippingCents,
      isAutoGenerated: input.isAutoGenerated ?? false,
      createdByMemberId: actor.memberId,
      submittedAt: null,
      approvedByMemberId: null,
      approvedAt: null,
      supplierNotifiedAt: null,
      expectedDeliveryDate: input.expectedDeliveryDate ?? null,
      notes: input.notes ?? null,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };

    await store.insertPo(header);
    await store.insertPoItems(
      organizationId,
      input.items.map((item) => ({
        id: randomUUID(),
        purchaseOrderId: poId,
        productVariantId: item.productVariantId,
        sku: '',
        variantName: '',
        orderedQty: item.orderedQty,
        receivedQty: 0,
        unitCostCents: item.unitCostCents,
        currency: input.currency,
      })),
    );

    await store.recordAudit({
      organizationId,
      actorMemberId: actor.memberId,
      actorRole: actor.role,
      action: 'PO_DRAFT_CREATED',
      entityType: 'purchase_orders',
      entityId: poId,
      correlationId: actor.correlationId,
      afterState: { poNumber: header.poNumber, subtotalCents, taxCents, shippingCents: input.shippingCents },
    });

    return header;
  },

  async submitPo(store: CommerceStore, organizationId: string, poId: string, actor: PoActor, notes?: string): Promise<PoHeader> {
    const po = await store.lockPo(organizationId, poId);
    if (!po) throw new PoNotFoundError(poId);
    if (po.status !== 'DRAFT') {
      throw new PoStateError(`Purchase order ${po.poNumber} is ${po.status}; only DRAFT orders can be submitted.`);
    }
    await store.updatePo(poId, { status: 'SUBMITTED', submittedAt: new Date().toISOString() });
    await store.recordAudit({
      organizationId,
      actorMemberId: actor.memberId,
      actorRole: actor.role,
      action: 'PO_SUBMITTED',
      entityType: 'purchase_orders',
      entityId: poId,
      correlationId: actor.correlationId,
      reason: notes ?? null,
      beforeState: { status: po.status },
      afterState: { status: 'SUBMITTED' },
    });
    return { ...po, status: 'SUBMITTED' };
  },

  async decidePoApproval(
    store: CommerceStore,
    organizationId: string,
    poId: string,
    actor: PoActor,
    input: { decision: 'APPROVE' | 'REJECT'; reason?: string },
  ): Promise<PoHeader> {
    // Rule 126 — separation of duties.
    if (actor.role !== 'OWNER' && actor.role !== 'MANAGER') {
      throw new PoForbiddenError('Only an OWNER or MANAGER may approve or reject a purchase order.');
    }
    const po = await store.lockPo(organizationId, poId);
    if (!po) throw new PoNotFoundError(poId);
    if (po.status !== 'SUBMITTED') {
      throw new PoStateError(`Purchase order ${po.poNumber} is ${po.status}; only SUBMITTED orders can be decided.`);
    }

    if (input.decision === 'REJECT') {
      await store.updatePo(poId, { status: 'REJECTED' });
      await store.recordAudit({
        organizationId,
        actorMemberId: actor.memberId,
        actorRole: actor.role,
        action: 'PO_REJECTED',
        entityType: 'purchase_orders',
        entityId: poId,
        correlationId: actor.correlationId,
        reason: input.reason ?? null,
        beforeState: { status: 'SUBMITTED' },
        afterState: { status: 'REJECTED' },
      });
      return { ...po, status: 'REJECTED' };
    }

    const now = new Date().toISOString();
    await store.updatePo(poId, {
      status: 'ORDERED',
      approvedByMemberId: actor.memberId,
      approvedAt: now,
      supplierNotifiedAt: now,
    });
    // Rule 142 — notify the supplier via the transactional outbox.
    await store.insertOutbox({
      organizationId,
      eventType: 'SUPPLIER_PO_EMAIL',
      dedupKey: `supplier_po_email:${poId}`,
      payload: { purchaseOrderId: poId, poNumber: po.poNumber, supplierId: po.supplierId },
    });
    await store.recordAudit({
      organizationId,
      actorMemberId: actor.memberId,
      actorRole: actor.role,
      action: 'PO_APPROVED_AND_ORDERED',
      entityType: 'purchase_orders',
      entityId: poId,
      correlationId: actor.correlationId,
      beforeState: { status: 'SUBMITTED' },
      afterState: { status: 'ORDERED', approvedByMemberId: actor.memberId },
    });
    return { ...po, status: 'ORDERED' };
  },

  /**
   * Atomic, pessimistically locked stock receipt (Rules 075–080, 147).
   * The caller must already hold the store lock (PG transaction / runExclusive).
   */
  async receivePurchaseOrderStock(
    store: CommerceStore,
    organizationId: string,
    poId: string,
    actor: PoActor,
    input: ReceivePoInput,
  ): Promise<{ purchaseOrder: PoHeader; movements: ReferenceMovement[] }> {
    const po = await store.lockPo(organizationId, poId); // Rule 076
    if (!po) throw new PoNotFoundError(poId);

    const items = await store.listPoItems(organizationId, poId); // variant ASC (Rule 077)
    const itemByVariant = new Map(items.map((item) => [item.productVariantId, item]));

    const conflicted: OverReceiptLine[] = [];
    for (const incoming of input.items) {
      if (incoming.receiveQty <= 0) continue;
      const item = itemByVariant.get(incoming.productVariantId);
      const orderedQty = item?.orderedQty ?? 0;
      const alreadyReceivedQty = item?.receivedQty ?? 0;
      if (!item || alreadyReceivedQty + incoming.receiveQty > orderedQty) {
        conflicted.push({
          productVariantId: incoming.productVariantId,
          sku: item?.sku ?? '',
          orderedQty,
          alreadyReceivedQty,
          attemptedQty: incoming.receiveQty,
          remainingReceivableQty: Math.max(0, orderedQty - alreadyReceivedQty),
        });
      }
    }

    const alreadyComplete = po.status === 'RECEIVED';
    if (alreadyComplete || conflicted.length > 0) {
      throw new PoOverReceiptConflictError(
        alreadyComplete
          ? `Purchase order ${po.poNumber} has already been fully received.`
          : `Receipt exceeds the ordered quantity for purchase order ${po.poNumber}.`,
        {
          status: po.status as PoStatus,
          poNumber: po.poNumber,
          lines:
            conflicted.length > 0
              ? conflicted
              : items.map((item) => ({
                  productVariantId: item.productVariantId,
                  sku: item.sku,
                  orderedQty: item.orderedQty,
                  alreadyReceivedQty: item.receivedQty,
                  attemptedQty: 0,
                  remainingReceivableQty: Math.max(0, item.orderedQty - item.receivedQty),
                })),
        },
      );
    }

    if (po.status !== 'ORDERED' && po.status !== 'PARTIALLY_RECEIVED') {
      throw new PoStateError(
        `Purchase order ${po.poNumber} is ${po.status}; stock can only be received on ORDERED or PARTIALLY_RECEIVED orders.`,
      );
    }

    const receivable = input.items
      .filter((incoming) => incoming.receiveQty > 0)
      .sort((a, b) => a.productVariantId.localeCompare(b.productVariantId));

    await InventoryLedgerService.applyMovement(store, {
      organizationId,
      locationId: po.locationId,
      movementType: 'PO_RECEIPT',
      referenceType: 'PURCHASE_ORDER',
      referenceId: poId,
      actorMemberId: actor.memberId,
      idempotencyKey: `po-receipt:${poId}:${actor.correlationId}`,
      currency: po.currency,
      notes: input.receiptNotes ?? null,
      items: receivable.map((incoming) => ({
        productVariantId: incoming.productVariantId,
        quantityDelta: incoming.receiveQty,
        unitCostCents: itemByVariant.get(incoming.productVariantId)?.unitCostCents,
      })),
    });

    const before = items.map((item) => ({ productVariantId: item.productVariantId, receivedQty: item.receivedQty }));
    for (const incoming of receivable) {
      const item = itemByVariant.get(incoming.productVariantId);
      if (!item) continue;
      await store.updatePoItem(item.id, { receivedQty: item.receivedQty + incoming.receiveQty });
    }

    const refreshed = await store.listPoItems(organizationId, poId);
    const fullyReceived = refreshed.every((item) => item.receivedQty >= item.orderedQty);
    const nextStatus: PoStatus = fullyReceived ? 'RECEIVED' : 'PARTIALLY_RECEIVED';
    await store.updatePo(poId, { status: nextStatus });

    await store.recordAudit({
      organizationId,
      actorMemberId: actor.memberId,
      actorRole: actor.role,
      action: 'PO_STOCK_RECEIVED',
      entityType: 'purchase_orders',
      entityId: poId,
      correlationId: actor.correlationId,
      beforeState: { status: po.status, items: before },
      afterState: {
        status: nextStatus,
        items: refreshed.map((item) => ({ productVariantId: item.productVariantId, receivedQty: item.receivedQty })),
      },
    });

    const movements = await store.listMovementsForReference(organizationId, poId);
    return { purchaseOrder: { ...po, status: nextStatus, updatedAt: new Date().toISOString() }, movements };
  },
};
