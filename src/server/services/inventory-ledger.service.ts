  private readonly soById = new Map<string, SoHeader>();
  private readonly soItemsBySo = new Map<string, SoItem[]>();
  private readonly adjustmentById = new Map<string, AdjustmentRecord>();
  private readonly thresholds = new Map<string, OrganizationThresholds>();
  private movementSeq = 0;
  private poSeq = 0;
  private soSeq = 0;
  private adjustmentSeq = 0;
  private queue: Promise<unknown> = Promise.resolve();

  private balanceKey(locationId: string, productVariantId: string): string {
    return `${locationId}:${productVariantId}`;
  }

  /** Serialize a unit of work so concurrent callers never interleave (the lock). */
  runExclusive<T>(fn: (store: CommerceStore) => Promise<T>): Promise<T> {
    const run = this.queue.then(() => fn(this));
    this.queue = run.then(
      () => undefined,
      () => undefined,
    );
    return run;
  }

  // Seeding helpers for tests / demo fixtures.
  seedVariant(variant: MemoryVariant): void {
    this.variants.set(variant.id, variant);
  }

  seedBalance(input: {
    organizationId: string;
    locationId: string;
    productVariantId: string;
    onHandQty: number;
    reservedQty?: number;
  }): void {
    this.balances.set(this.balanceKey(input.locationId, input.productVariantId), {
      organizationId: input.organizationId,
      locationId: input.locationId,
      productVariantId: input.productVariantId,
      onHandQty: input.onHandQty,
      reservedQty: input.reservedQty ?? 0,
      version: 1,
      lastMovementId: null,
    });
  }

  balances_(): MemoryBalance[] {
    return [...this.balances.values()];
  }

  getBalance(locationId: string, productVariantId: string): MemoryBalance | null {
    return this.balances.get(this.balanceKey(locationId, productVariantId)) ?? null;
  }

  movements(): readonly MemoryMovement[] {
    return this.movementLog;
  }

  audits_(): readonly AuditInput[] {
    return this.audits;
  }

  outbox_(): OutboxEventRow[] {
    return [...this.outbox.values()];
  }

  seedLocation(id: string, code: string, name: string): void {
    this.locationsById.set(id, { code, name });
  }

  async lockBalances(organizationId: string, locationId: string, variantIds: string[]): Promise<LockedBalance[]> {
    const ordered = sortVariantIdsDeterministically(variantIds);
    return ordered.map((productVariantId) => {
      const key = this.balanceKey(locationId, productVariantId);
      let balance = this.balances.get(key);
      if (!balance) {
        balance = { organizationId, locationId, productVariantId, onHandQty: 0, reservedQty: 0, version: 1, lastMovementId: null };
        this.balances.set(key, balance);
      }
      const variant = this.variants.get(productVariantId);
      return {
        productVariantId,
        locationId,
        onHandQty: balance.onHandQty,
        reservedQty: balance.reservedQty,
        availableQty: balance.onHandQty - balance.reservedQty,
        version: balance.version,
        sku: variant?.sku ?? '',
        variantName: variant?.variantName ?? '',
        reorderPoint: variant?.reorderPoint ?? 0,
        currency: variant?.currency ?? 'USD',
        unitCostCents: variant?.unitCostCents ?? 0,
        sellingPriceCents: variant?.sellingPriceCents ?? 0,
      };
    });
  }

  async insertMovement(input: MovementInput): Promise<{ id: number }> {
    this.movementSeq += 1;
    const id = this.movementSeq;
    this.movementLog.push({ ...input, id });
    return { id };
  }

  async updateBalance(
    organizationId: string,
    locationId: string,
    productVariantId: string,
    patch: { onHandQty?: number; reservedQty?: number; lastMovementId?: number | null },
  ): Promise<void> {
    const balance = this.balances.get(this.balanceKey(locationId, productVariantId));
    if (!balance || balance.organizationId !== organizationId) return;
    if (patch.onHandQty !== undefined) balance.onHandQty = patch.onHandQty;
    if (patch.reservedQty !== undefined) balance.reservedQty = patch.reservedQty;
    if (patch.lastMovementId !== undefined) balance.lastMovementId = patch.lastMovementId;
    balance.version += 1;
  }

