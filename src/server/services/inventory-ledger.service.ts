/**
 * Run a commerce operation on PostgreSQL, falling back to the seeded in-memory
 * store in dev/demo when the database is unreachable. Domain errors (which all
 * carry a numeric `status`) always propagate; only infrastructure failures fall back.
 */
export async function withCommerceStore<T>(fn: (store: CommerceStore) => Promise<T>): Promise<T> {
  try {
    return await withTransaction((tx: DbTransaction) => fn(new PostgresCommerceStore(tx)));
  } catch (error) {
    if (getPublicEnv().NEXT_PUBLIC_APP_ENV === 'prod') throw error;
    const status = (error as { status?: unknown }).status;
    if (typeof status === 'number') throw error;
    console.warn('[commerce] PostgreSQL unavailable — using the seeded demo store.');
    return getDemoCommerceStore().runExclusive(fn);
  }
}
