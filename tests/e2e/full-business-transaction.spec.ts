import { describe, expect, it, vi } from 'vitest';
import { InMemoryCommerceStore } from '../../src/server/services/inventory-ledger.service';
import { PurchaseOrderService, PoOverReceiptConflictError } from '../../src/server/services/purchase-order.service';
import { SalesOrderService, SalesOversellConflictError } from '../../src/server/services/sales-order.service';
import { AdjustmentService } from '../../src/server/services/adjustment.service';
import { AutomationService } from '../../src/server/services/automation.service';
import { InMemoryCsvCommitAdapter, commitValidRows, validateCsv } from '../../src/server/services/csv-import.service';
import { InMemoryIdempotencyStorageAdapter, runIdempotent } from '../../src/server/middleware/with-idempotency';

// `server-only` throws outside a React Server bundle — neutralise it for tests.
vi.mock('server-only', () => ({}));

const ORG = 'org-e2e';
const LOC = 'loc-e2e';
const SUPPLIER = 'sup-e2e';
const GPU = 'variant-gpu';
const CPU = 'variant-cpu';

const PROCUREMENT = { memberId: 'm-proc', role: 'PROCUREMENT_OFFICER' as const, correlationId: 'corr-proc' };
const MANAGER = { memberId: 'm-mgr', role: 'MANAGER' as const, correlationId: 'corr-mgr' };
const CLERK_A = { memberId: 'm-clerk-a', role: 'WAREHOUSE_CLERK' as const, correlationId: 'corr-clerk-a' };
const CLERK_B = { memberId: 'm-clerk-b', role: 'WAREHOUSE_CLERK' as const, correlationId: 'corr-clerk-b' };
const SALES = { memberId: 'm-sales', role: 'SALES_ASSOCIATE' as const, correlationId: 'corr-sales' };

function freshStore(): InMemoryCommerceStore {
  const store = new InMemoryCommerceStore();
  store.seedOrganizationThresholds(ORG, { suspiciousAdjThresholdCents: 50_000, suspiciousAdjPctBps: 1_000 });
  store.seedLocation(LOC, 'WH-CENTRAL', 'Main Warehouse — Austin');
  store.seedLocation('loc-east', 'STORE-MAIN', 'East Distribution — Raleigh');
  store.seedVariant({ id: GPU, organizationId: ORG, sku: 'GPU-E2E-4090', variantName: 'ASUS TUF RTX 4090', category: 'GPUs', isActive: true, reorderPoint: 5, reorderQty: 25, primarySupplierId: SUPPLIER, currency: 'USD', unitCostCents: 165_000, sellingPriceCents: 189_999 });
  store.seedVariant({ id: CPU, organizationId: ORG, sku: 'CPU-E2E-7800X3D', variantName: 'AMD Ryzen 7 7800X3D', category: 'CPUs', isActive: true, reorderPoint: 5, reorderQty: 20, primarySupplierId: SUPPLIER, currency: 'USD', unitCostCents: 34_000, sellingPriceCents: 39_999 });
  store.seedBalance({ organizationId: ORG, locationId: LOC, productVariantId: GPU, onHandQty: 0 });
  store.seedBalance({ organizationId: ORG, locationId: LOC, productVariantId: CPU, onHandQty: 0 });
  return store;
}

const HEADER = 'sku,name,brand,category,supplier_code,unit_cost,selling_price,currency,reorder_point,reorder_qty,barcode_upc';

describe('Full business transaction lifecycle (Phase 7 · Step 21)', () => {
  it('executes all 8 stages end to end with intact ledger invariants', async () => {
    const store = freshStore();
    let purchaseOrderId = '';
    let salesOrderId = '';

    // ── Stage 1: bulk CSV catalog import + formula-injection defence ──
    const csv = [
      HEADER,
      'GPU-E2E-NEW,RTX 5090 32GB,ASUS,GPUs,SUP-E2E,1999.00,2299.00,USD,5,10,',
      'SSD-E2E-NEW,Samsung 9100 4TB,Samsung,Storage,SUP-E2E,299.00,349.00,USD,5,20,',
      '=CMD(),Injected,Acme,GPUs,SUP-E2E,10.00,20.00,USD,5,10,',
      'BAD SKU!,Malformed,Acme,GPUs,SUP-E2E,10.00,20.00,USD,5,10,',
    ].join('\r\n');
    const validation = validateCsv({ csvText: csv, knownSupplierCodes: new Set(['SUP-E2E']) });
    expect(validation.summary.validCount).toBe(2);
    expect(validation.summary.invalidCount).toBe(2);
    expect(validation.invalidRows.map((row) => row.rowNumber)).toEqual([4, 5]);
    expect(validation.invalidRows[0].errors[0].code).toBe('FORMULA_INJECTION_BLOCKED');

    const csvAdapter = new InMemoryCsvCommitAdapter();
    const firstCommit = await commitValidRows(ORG, { memberId: 'm-mgr', role: 'MANAGER', correlationId: 'corr-csv' }, validation.validRows, { adapter: csvAdapter, rejectedInvalidCount: 2, totalUploaded: 4 });
    const replayCommit = await commitValidRows(ORG, { memberId: 'm-mgr', role: 'MANAGER', correlationId: 'corr-csv' }, validation.validRows, { adapter: csvAdapter, rejectedInvalidCount: 2, totalUploaded: 4 });
    expect(firstCommit.importedValidCount).toBe(2);
    expect(replayCommit.importedValidCount).toBe(0);
    expect(replayCommit.skippedExistingCount).toBe(2);

    // ── Stage 2: PO drafting, submission & separation of duties ──
    const po = await store.runExclusive((s) =>
      PurchaseOrderService.createDraftPo(s, ORG, PROCUREMENT, {
        supplierId: SUPPLIER,
        locationId: LOC,
        currency: 'USD',
        shippingCents: 0,
        isAutoGenerated: false,
        items: [{ productVariantId: GPU, orderedQty: 10, unitCostCents: 165_000 }],
      }),
    );
    purchaseOrderId = po.id;
    expect(po.status).toBe('DRAFT');

    const submitted = await store.runExclusive((s) => PurchaseOrderService.submitPo(s, ORG, purchaseOrderId, PROCUREMENT));
    expect(submitted.status).toBe('SUBMITTED');

    await expect(
      store.runExclusive((s) => PurchaseOrderService.decidePoApproval(s, ORG, purchaseOrderId, PROCUREMENT, { decision: 'APPROVE' })),
    ).rejects.toMatchObject({ code: 'FORBIDDEN' });

    const approved = await store.runExclusive((s) => PurchaseOrderService.decidePoApproval(s, ORG, purchaseOrderId, MANAGER, { decision: 'APPROVE' }));
    expect(approved.status).toBe('ORDERED');
    expect(store.outbox_().some((event) => event.eventType === 'SUPPLIER_PO_EMAIL')).toBe(true);

    // ── Stage 3: concurrent 2-clerk receipt serialization ──
    const receive = (actor: typeof CLERK_A, qty: number) =>
      store.runExclusive((s) =>
        PurchaseOrderService.receivePurchaseOrderStock(s, ORG, purchaseOrderId, actor, { items: [{ productVariantId: GPU, receiveQty: qty }] }),
      );
    const race = await Promise.allSettled([receive(CLERK_A, 6), receive(CLERK_B, 6)]);
    const winner = race.find((result) => result.status === 'fulfilled');
    const loser = race.find((result) => result.status === 'rejected');
    expect(winner?.status).toBe('fulfilled');
    if (winner?.status === 'fulfilled') expect(winner.value.purchaseOrder.status).toBe('PARTIALLY_RECEIVED');
    expect(loser?.status).toBe('rejected');
    if (loser?.status === 'rejected') {
      expect(loser.reason).toBeInstanceOf(PoOverReceiptConflictError);
      expect((loser.reason as PoOverReceiptConflictError).details.lines[0].remainingReceivableQty).toBe(4);
    }

    const reconciled = await receive(CLERK_B, 4);
    expect(reconciled.purchaseOrder.status).toBe('RECEIVED');
    expect(store.getBalance(LOC, GPU)?.onHandQty).toBe(10);

    // ── Stage 4: idempotent network-fluctuation replay ──
    const idempotency = new InMemoryIdempotencyStorageAdapter();
    const key = 'sp_idem_e2e_receipt_0001';
    let executions = 0;
    const execute = async () => {
      executions += 1;
      return { status: 200, body: { data: { replayedHandler: true } } };
    };
    const first = await runIdempotent({ adapter: idempotency, organizationId: ORG, memberId: CLERK_B.memberId, method: 'POST', pathname: '/api/v1/purchase-orders/x/receive', idempotencyKey: key, rawBody: '{"items":[]}', execute });
    const replay = await runIdempotent({ adapter: idempotency, organizationId: ORG, memberId: CLERK_B.memberId, method: 'POST', pathname: '/api/v1/purchase-orders/x/receive', idempotencyKey: key, rawBody: '{"items":[]}', execute });
    expect(first.replayed).toBe(false);
    expect(replay.replayed).toBe(true);
    expect(executions).toBe(1);
    expect(store.getBalance(LOC, GPU)?.onHandQty).toBe(10); // never double-incremented

    // ── Stage 5: SO reservation, oversell protection & fulfillment ──
    const so = await store.runExclusive((s) =>
      SalesOrderService.createAndConfirmSalesOrder(s, ORG, SALES, {
        locationId: LOC,
        customerName: 'Acme Studios LLC',
        currency: 'USD',
        taxRateBps: 0,
        discountCents: 0,
        confirmImmediately: true,
        items: [{ productVariantId: GPU, quantity: 8 }],
      }),
    );
    salesOrderId = so.id;
    expect(so.status).toBe('CONFIRMED');
    expect((store.getBalance(LOC, GPU)?.onHandQty ?? 0) - (store.getBalance(LOC, GPU)?.reservedQty ?? 0)).toBe(2);

    await expect(
      store.runExclusive((s) =>
        SalesOrderService.createAndConfirmSalesOrder(s, ORG, SALES, {
          locationId: LOC,
          customerName: 'Rival Reseller',
          currency: 'USD',
          taxRateBps: 0,
          discountCents: 0,
          confirmImmediately: true,
          items: [{ productVariantId: GPU, quantity: 5 }],
        }),
      ),
    ).rejects.toBeInstanceOf(SalesOversellConflictError);

    const fulfilled = await store.runExclusive((s) => SalesOrderService.fulfillSalesOrder(s, ORG, salesOrderId, CLERK_A));
    expect(fulfilled.status).toBe('FULFILLED');
    const fulfillment = store.movements().filter((movement) => movement.movementType === 'SALE_FULFILLMENT');
    expect(fulfillment).toHaveLength(1);
    expect(fulfillment[0].quantityDelta).toBe(-8);
    expect(store.getBalance(LOC, GPU)?.onHandQty).toBe(2);
    expect(store.outbox_().some((event) => event.eventType === 'LOW_STOCK_ALERT')).toBe(true);
    expect(store.outbox_().some((event) => event.eventType === 'AUTO_DRAFT_PO')).toBe(true);

    // ── Stage 6: automated outbox processing (low-stock alert + auto-draft PO) ──
    const firstRun = await store.runExclusive((s) => AutomationService.processPendingOutboxEvents(s, ORG, 50));
    expect(firstRun.processedCount).toBeGreaterThan(0);
    expect(firstRun.autoDraftedPoIds.length).toBe(1);

    const autoPos = store.poItems(firstRun.autoDraftedPoIds[0]);
    expect(autoPos[0].orderedQty).toBe(25); // reorderQty

    const secondRun = await store.runExclusive((s) => AutomationService.processPendingOutboxEvents(s, ORG, 50));
    void secondRun;
    const totalAutoPos = (await store.listPos(ORG, {})).filter((row) => row.isAutoGenerated);
    expect(totalAutoPos).toHaveLength(1); // deduplicated — no duplicate auto-PO

    // ── Stage 7: suspicious adjustment flagging + manager reversal ──
    const adjustment = await store.runExclusive((s) =>
      AdjustmentService.createStockAdjustment(s, ORG, CLERK_A, 'adj-e2e-1', {
        locationId: LOC,
        productVariantId: GPU,
        quantityDelta: -1,
        reasonCode: 'THEFT_SHRINKAGE',
        reasonNotes: 'One unit missing after the quarterly cage recount.',
      }),
    );
    expect(adjustment.isSuspicious).toBe(true);
    expect(adjustment.status).toBe('PENDING_APPROVAL');
    expect(adjustment.suspiciousTriggerReasons).toContain('VALUE_EXCEEDS_THRESHOLD');
    expect(store.outbox_().some((event) => event.eventType === 'SUSPICIOUS_ADJ_ALERT')).toBe(true);
    const afterAdjustment = store.getBalance(LOC, GPU)?.onHandQty;
    expect(afterAdjustment).toBe(1);

    const reviewed = await store.runExclusive((s) =>
      AdjustmentService.reviewSuspiciousAdjustment(s, ORG, adjustment.id, MANAGER, {
        decision: 'REJECT',
        reviewNotes: 'Recount required before writing off.',
      }),
    );
    expect(reviewed.status).toBe('REJECTED');
    expect(store.getBalance(LOC, GPU)?.onHandQty).toBe(2); // compensating reversal posted

    // ── Stage 8: daily report + global ledger invariants ──
    const report = await store.runExclusive((s) => AutomationService.generateDailySalesAndValuationReport(s, ORG));
    expect(report.currency).toBe('USD');
    expect(report.salesMetrics.fulfilledOrdersCount).toBe(1);
    expect(report.salesMetrics.grossRevenueCents).toBe(8 * 189_999);
    expect(report.salesMetrics.cogsCents).toBe(8 * 165_000);
    expect(report.inventoryMetrics.totalActiveSkus).toBeGreaterThan(0);
    expect(report.locationBreakdown.length).toBeGreaterThan(0);
    expect(report.topMovingSkus.length).toBeGreaterThan(0);

    // Rule 066 — SUM(quantity_delta) === on_hand_qty for EVERY SKU/location.
    for (const balance of store.balances_()) {
      const delta = store
        .movements()
        .filter((movement) => movement.locationId === balance.locationId && movement.productVariantId === balance.productVariantId)
        .reduce((total, movement) => total + movement.quantityDelta, 0);
      expect(delta).toBe(balance.onHandQty); // Rule 066
      expect(balance.onHandQty).toBeGreaterThanOrEqual(0); // Rule 068
      expect(balance.reservedQty).toBeGreaterThanOrEqual(0); // Rule 069
      expect(balance.onHandQty).toBeGreaterThanOrEqual(balance.reservedQty); // Rule 070
      expect(balance.onHandQty - balance.reservedQty).toBeGreaterThanOrEqual(0); // Rule 067
    }
  });
});
