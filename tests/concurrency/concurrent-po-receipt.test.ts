import { describe, expect, it, vi } from 'vitest';
import { InMemoryCommerceStore } from '../../src/server/services/inventory-ledger.service';
import {
  PoOverReceiptConflictError,
  PurchaseOrderService,
} from '../../src/server/services/purchase-order.service';

// `server-only` throws outside a React Server bundle — neutralise it for tests.
vi.mock('server-only', () => ({}));

const ORG = 'org-1';
const LOC = 'loc-1';
const VARIANT = 'variant-1';
const PO = 'po-1';
const SKU = 'GPU-TEST-001';

const ACTOR = { memberId: 'm1', role: 'WAREHOUSE_CLERK' as const, correlationId: 'corr-receipt' };

function makeStore(status: string, orderedQty = 10): InMemoryCommerceStore {
  const store = new InMemoryCommerceStore();
  store.seedVariant({
    id: VARIANT,
    organizationId: ORG,
    sku: SKU,
    reorderPoint: 5,
    currency: 'USD',
    unitCostCents: 1000,
  });
  store.seedBalance({ organizationId: ORG, locationId: LOC, productVariantId: VARIANT, onHandQty: 0 });
  store.seedPo(
    {
      id: PO,
      organizationId: ORG,
      poNumber: 'PO-2026-0001',
      supplierId: 'sup-1',
      locationId: LOC,
      status,
      currency: 'USD',
      subtotalCents: orderedQty * 1000,
      taxCents: 0,
      shippingCents: 0,
      totalCents: orderedQty * 1000,
      isAutoGenerated: false,
      createdByMemberId: 'm1',
      submittedAt: null,
      approvedByMemberId: null,
      approvedAt: null,
      supplierNotifiedAt: null,
      expectedDeliveryDate: null,
      notes: null,
      createdAt: new Date(0).toISOString(),
      updatedAt: new Date(0).toISOString(),
    },
    [
      {
        id: 'item-1',
        purchaseOrderId: PO,
        productVariantId: VARIANT,
        sku: SKU,
        variantName: 'Test GPU',
        orderedQty,
        receivedQty: 0,
        unitCostCents: 1000,
        currency: 'USD',
      },
    ],
  );
  return store;
}

function receive(store: InMemoryCommerceStore, qty: number) {
  return store.runExclusive((s) =>
    PurchaseOrderService.receivePurchaseOrderStock(s, ORG, PO, ACTOR, {
      items: [{ productVariantId: VARIANT, receiveQty: qty }],
    }),
  );
}

describe('Concurrent purchase order receipt (Rule 147)', () => {
  it('Test 1 — two clerks receiving 10 units on a 10-unit PO: one wins, one is blocked', async () => {
    const store = makeStore('ORDERED', 10);

    const results = await Promise.allSettled([receive(store, 10), receive(store, 10)]);
    const fulfilled = results.filter((result) => result.status === 'fulfilled');
    const rejected = results.filter((result) => result.status === 'rejected');

    expect(fulfilled).toHaveLength(1);
    expect(rejected).toHaveLength(1);
    const winner = fulfilled[0];
    if (winner.status !== 'fulfilled') throw new Error('expected a fulfilled receipt');
    expect(winner.value.purchaseOrder.status).toBe('RECEIVED');

    const failure = rejected[0].status === 'rejected' ? rejected[0].reason : null;
    expect(failure).toBeInstanceOf(PoOverReceiptConflictError);
    const conflict = failure as PoOverReceiptConflictError;
    expect(conflict.code).toBe('OVER_RECEIPT_PREVENTED');
    expect(conflict.status).toBe(409);
    expect(conflict.details.status).toBe('RECEIVED');
    expect(conflict.details.lines[0].remainingReceivableQty).toBe(0);

    const receipts = store.movements().filter((movement) => movement.movementType === 'PO_RECEIPT');
    expect(receipts).toHaveLength(1);
    expect(receipts[0].quantityDelta).toBe(10);
    expect(store.getBalance(LOC, VARIANT)?.onHandQty).toBe(10);
  });

  it('Test 2 — 6 + 6 on a 10-unit PO, then reconcile the remaining 4', async () => {
    const store = makeStore('ORDERED', 10);

    const [a, b] = await Promise.allSettled([receive(store, 6), receive(store, 6)]);

    const fulfilled = a.status === 'fulfilled' ? a.value : b.status === 'fulfilled' ? b.value : null;
    const failure = a.status === 'rejected' ? a.reason : b.status === 'rejected' ? b.reason : null;

    expect(fulfilled).not.toBeNull();
    expect(fulfilled?.purchaseOrder.status).toBe('PARTIALLY_RECEIVED');

    const items = store.poItems(PO);
    expect(items[0].receivedQty).toBe(6);
    expect(items[0].orderedQty - items[0].receivedQty).toBe(4);

    expect(failure).toBeInstanceOf(PoOverReceiptConflictError);
    const conflict = failure as PoOverReceiptConflictError;
    expect(conflict.code).toBe('OVER_RECEIPT_PREVENTED');
    expect(conflict.details.lines[0].remainingReceivableQty).toBe(4);

    // Clerk B reconciles with the exact remaining quantity.
    const reconciled = await receive(store, 4);
    expect(reconciled.purchaseOrder.status).toBe('RECEIVED');
    expect(store.getBalance(LOC, VARIANT)?.onHandQty).toBe(10);

    const totalDelta = store
      .movements()
      .filter((movement) => movement.movementType === 'PO_RECEIPT')
      .reduce((sum, movement) => sum + movement.quantityDelta, 0);
    expect(totalDelta).toBe(10);
  });

  it('Test 3 — receiving on DRAFT / SUBMITTED / REJECTED orders is rejected with zero ledger writes', async () => {
    for (const status of ['DRAFT', 'SUBMITTED', 'REJECTED']) {
      const store = makeStore(status, 10);
      await expect(receive(store, 5)).rejects.toMatchObject({ code: 'INVALID_PO_STATE_TRANSITION' });
      expect(store.movements()).toHaveLength(0);
      expect(store.getBalance(LOC, VARIANT)?.onHandQty).toBe(0);
    }
  });
});
